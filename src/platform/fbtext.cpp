#include "platform/fbtext.h"
#include <pspdisplay.h>

// 0 to F plus blank, five wide inside an eight cell, drawn at double size.
static const unsigned char kGlyph[17][8] = {
    { 0x3C,0x66,0x6E,0x7E,0x76,0x66,0x3C,0x00 },
    { 0x18,0x38,0x18,0x18,0x18,0x18,0x7E,0x00 },
    { 0x3C,0x66,0x06,0x0C,0x30,0x60,0x7E,0x00 },
    { 0x3C,0x66,0x06,0x1C,0x06,0x66,0x3C,0x00 },
    { 0x0C,0x1C,0x3C,0x6C,0x7E,0x0C,0x0C,0x00 },
    { 0x7E,0x60,0x7C,0x06,0x06,0x66,0x3C,0x00 },
    { 0x1C,0x30,0x60,0x7C,0x66,0x66,0x3C,0x00 },
    { 0x7E,0x66,0x0C,0x18,0x18,0x18,0x18,0x00 },
    { 0x3C,0x66,0x66,0x3C,0x66,0x66,0x3C,0x00 },
    { 0x3C,0x66,0x66,0x3E,0x06,0x0C,0x38,0x00 },
    { 0x18,0x3C,0x66,0x66,0x7E,0x66,0x66,0x00 },
    { 0x7C,0x66,0x66,0x7C,0x66,0x66,0x7C,0x00 },
    { 0x3C,0x66,0x60,0x60,0x60,0x66,0x3C,0x00 },
    { 0x78,0x6C,0x66,0x66,0x66,0x6C,0x78,0x00 },
    { 0x7E,0x60,0x60,0x7C,0x60,0x60,0x7E,0x00 },
    { 0x7E,0x60,0x60,0x7C,0x60,0x60,0x60,0x00 },
    { 0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00 },
};

enum { CELL_W = 16, CELL_H = 16, SCALE = 2, ROW0_Y = 200 };

static unsigned short* s_fb = 0;
static int s_bw = 0;

void fbTextFrameBegin(void) {
    void* fb = 0; int bw = 0, pf = 0;
    if (sceDisplayGetFrameBuf(&fb, &bw, &pf, PSP_DISPLAY_SETBUF_IMMEDIATE) < 0
        || !fb || bw <= 0) { s_fb = 0; return; }
    s_fb = (unsigned short*)((unsigned int)fb | 0x40000000u);
    s_bw = bw;
}

static void glyph(int px, int py, int g) {
    if (px < 0 || py < 0 || px + CELL_W > 480 || py + CELL_H > 272) return;
    const unsigned char* rows = kGlyph[g];
    for (int y = 0; y < 8; y++) {
        unsigned char bits = rows[y];
        for (int s = 0; s < SCALE; s++) {
            unsigned short* p = s_fb + (py + y * SCALE + s) * s_bw + px;
            for (int x = 0; x < 8; x++) {
                unsigned short c = (bits & (0x80 >> x)) ? 0xFFFF : 0x8000;
                p[x * SCALE] = c;
                p[x * SCALE + 1] = c;
            }
        }
    }
}

void fbTextHex(int row, int col, unsigned int value, int digits) {
    if (!s_fb || digits < 1 || digits > 8) return;
    int py = ROW0_Y + row * CELL_H;
    for (int i = 0; i < digits; i++) {
        int nib = (int)((value >> ((digits - 1 - i) * 4)) & 0xF);
        glyph((col + i) * CELL_W, py, nib);
    }
}

void fbTextClear(int row) {
    if (!s_fb) return;
    int py = ROW0_Y + row * CELL_H;
    if (py < 0 || py + CELL_H > 272) return;
    for (int y = 0; y < CELL_H; y++) {
        unsigned short* p = s_fb + (py + y) * s_bw;
        for (int x = 0; x < 480; x++) p[x] = 0x8000;
    }
}
